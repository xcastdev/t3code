// @effect-diagnostics nodeBuiltinImport:off - the SDK spawn hook retains actual child exit receipts.
import * as ClaudeSdk from "@anthropic-ai/claude-agent-sdk";
import * as NodeServices from "@effect/platform-node/NodeServices";
import { assert, it } from "@effect/vitest";
import { ClaudeSettings } from "@t3tools/contracts";
import * as NodeChildProcess from "node:child_process";
import * as NodeCrypto from "node:crypto";
import * as NodePath from "node:path";
import * as Cause from "effect/Cause";
import * as Deferred from "effect/Deferred";
import * as Effect from "effect/Effect";
import * as Exit from "effect/Exit";
import * as Fiber from "effect/Fiber";
import * as FileSystem from "effect/FileSystem";
import * as Schema from "effect/Schema";
import * as TestClock from "effect/testing/TestClock";
import { vi } from "vite-plus/test";

import { probeClaudeCapabilities } from "./ClaudeProvider.ts";

vi.mock("@anthropic-ai/claude-agent-sdk", { spy: true });

const decodeClaudeSettings = Schema.decodeSync(ClaudeSettings);
const encodeReceipt = Schema.encodeSync(Schema.fromJsonString(Schema.Unknown));

// Byte-for-byte the persistent peer generated by ProviderInstanceRegistryLive.test.ts.
// It ignores get_usage and EOF; cleanup must stop and join it without a user prompt.
const persistentFixture = [
  "#!/usr/bin/env node",
  'import * as NodeReadline from "node:readline";',
  'if (process.argv.includes("--version")) {',
  '  process.stdout.write("claude 2.1.219\\n");',
  "  process.exit(0);",
  "}",
  "const lines = NodeReadline.createInterface({ input: process.stdin });",
  'lines.on("line", (line) => {',
  "  const message = JSON.parse(line);",
  '  if (message.type !== "control_request" || message.request?.subtype !== "initialize") return;',
  "  process.stdout.write(JSON.stringify({",
  '    type: "control_response",',
  "    response: {",
  '      subtype: "success",',
  "      request_id: message.request_id,",
  "      response: {",
  "        commands: [], agents: [], models: [],",
  '        output_style: "default", available_output_styles: ["default"],',
  '        account: { email: "test@example.com", subscriptionType: "pro", tokenSource: "oauth" },',
  "      },",
  "    },",
  '  }) + "\\n");',
  "});",
  "setInterval(() => {}, 1_000);",
  "",
].join("\n");

type FixtureMode = "persistent" | "success" | "init-failure" | "init-timeout" | "usage-failure";

function fixtureFor(mode: FixtureMode): string {
  if (mode === "persistent") return persistentFixture;
  return persistentFixture.replace(
    '  if (message.type !== "control_request" || message.request?.subtype !== "initialize") return;',
    [
      '  if (message.type !== "control_request") return;',
      '  if (message.request?.subtype === "get_usage") {',
      '    process.stdout.write(JSON.stringify({ type: "control_response", response: {',
      mode === "usage-failure"
        ? '      subtype: "error", request_id: message.request_id, error: "usage refused",'
        : '      subtype: "success", request_id: message.request_id, response: { rate_limits_available: false, rate_limits: {} },',
      '    } }) + "\\n");',
      "    return;",
      "  }",
      '  if (message.request?.subtype !== "initialize") return;',
      ...(mode === "init-timeout" ? ["  return;"] : []),
      ...(mode === "init-failure"
        ? [
            '  process.stdout.write(JSON.stringify({ type: "control_response", response: { subtype: "error", request_id: message.request_id, error: "initialization refused" } }) + "\\n");',
            "  return;",
          ]
        : []),
    ].join("\n"),
  );
}

const cases = [
  { name: "persistent optional usage timeout", mode: "persistent", deadline: "usage" },
  { name: "readiness success", mode: "success" },
  { name: "initialization failure", mode: "init-failure", denied: true },
  { name: "initialization timeout", mode: "init-timeout", deadline: "init", denied: true },
  { name: "optional usage failure", mode: "usage-failure" },
  { name: "interruption during initialization", mode: "init-timeout", interrupt: "init" },
  { name: "interruption during optional usage", mode: "persistent", interrupt: "usage" },
  {
    name: "construction failure after spawn",
    mode: "success",
    constructionFailure: true,
    denied: true,
  },
  { name: "synchronous close failure", mode: "success", cleanupFailure: "close", denied: true },
  { name: "return failure", mode: "success", cleanupFailure: "return", denied: true },
] as const;

it.layer(NodeServices.layer)("Claude readiness query ownership", (it) => {
  it.effect.each(cases)("joins the actual persistent subprocess: $name", (testCase) =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const root = yield* fs.makeTempDirectoryScoped({ prefix: "t3-claude-readiness-" });
      const executable = NodePath.join(root, "claude");
      const home = NodePath.join(root, "home");
      const workspace = NodePath.join(root, "workspace");
      const tmp = NodePath.join(root, "tmp");
      for (const directory of [home, workspace, tmp]) yield* fs.makeDirectory(directory);
      yield* fs.writeFileString(executable, fixtureFor(testCase.mode));
      yield* fs.chmod(executable, 0o755);
      if (testCase.mode === "persistent") {
        assert.equal(Buffer.byteLength(persistentFixture), 848);
        assert.equal(
          NodeCrypto.createHash("sha256").update(persistentFixture).digest("hex"),
          "803d66c5c2af1641c00cac4a983888e31b6a0ffbf1c128b11713ff7a1434968b",
        );
      }
      const initStarted = yield* Deferred.make<void>();
      const usageStarted = yield* Deferred.make<void>();
      let child: NodeChildProcess.ChildProcessWithoutNullStreams | undefined;
      let exited = false;
      let closeCalled = false;
      let returnJoined = false;
      let abortSignal: AbortSignal | undefined;
      let exitReceipt: Promise<void> | undefined;
      const requests: string[] = [];
      const actualSdk = yield* Effect.promise(() =>
        vi.importActual<typeof ClaudeSdk>("@anthropic-ai/claude-agent-sdk"),
      );
      const query = vi.spyOn(ClaudeSdk, "query").mockImplementation((input) => {
        abortSignal = input.options?.abortController?.signal;
        const q = actualSdk.query({
          ...input,
          options: {
            ...input.options,
            spawnClaudeCodeProcess: (options) => {
              assert.equal(child, undefined);
              const spawn = input.options?.spawnClaudeCodeProcess;
              const spawned = (
                spawn === undefined
                  ? NodeChildProcess.spawn(options.command, options.args, {
                      cwd: options.cwd,
                      env: options.env,
                      signal: options.signal,
                      stdio: ["pipe", "pipe", "pipe"],
                      windowsHide: true,
                    })
                  : spawn(options)
              ) as NodeChildProcess.ChildProcessWithoutNullStreams;
              child = spawned;
              spawned.stderr.resume();
              exitReceipt = new Promise<void>((resolve) => {
                spawned.once("exit", () => {
                  exited = true;
                  resolve();
                });
              });
              const write = spawned.stdin.write.bind(spawned.stdin);
              vi.spyOn(spawned.stdin, "write").mockImplementation((...args) => {
                const message = JSON.parse(String(args[0])) as {
                  type: string;
                  request?: { subtype?: string };
                };
                requests.push(
                  message.type === "control_request"
                    ? (message.request?.subtype ?? "unknown")
                    : message.type,
                );
                if (message.request?.subtype === "initialize")
                  Deferred.doneUnsafe(initStarted, Effect.void);
                if (message.request?.subtype === "get_usage")
                  Deferred.doneUnsafe(usageStarted, Effect.void);
                return write(...args);
              });
              return spawned;
            },
          },
        });
        if ("constructionFailure" in testCase) throw new Error("construction failed after spawn");
        const close = q.close.bind(q);
        const finish = q.return.bind(q);
        q.close = () => {
          closeCalled = true;
          close();
          if ("cleanupFailure" in testCase && testCase.cleanupFailure === "close")
            throw new Error("close refused");
        };
        q.return = async (...args) => {
          const result = await finish(...args);
          returnJoined = true;
          if ("cleanupFailure" in testCase && testCase.cleanupFailure === "return")
            throw new Error("return refused");
          return result;
        };
        return q;
      });
      // Failure cleanup uses only the retained handle; success must already have its exit receipt.
      yield* Effect.addFinalizer(() =>
        Effect.gen(function* () {
          const exitedBeforeTeardown = exited;
          query.mockRestore();
          yield* Effect.promise(async () => {
            if (child !== undefined && !exited) child.kill("SIGTERM");
            await exitReceipt;
          });
          const evidenceDirectory = process.env.T3_CLAUDE_PROBE_EVIDENCE_DIR;
          if (evidenceDirectory !== undefined) {
            yield* fs
              .writeFileString(
                NodePath.join(evidenceDirectory, testCase.name.replaceAll(" ", "-") + ".json"),
                encodeReceipt({
                  name: testCase.name,
                  pid: child?.pid,
                  exitedBeforeTeardown,
                  exitedAfterTeardown: exited,
                  closeCalled,
                  returnJoined,
                  abortSignaled: abortSignal?.aborted,
                  requests,
                  fixtureSha256: NodeCrypto.createHash("sha256")
                    .update(fixtureFor(testCase.mode))
                    .digest("hex"),
                  parentHomeUntouched: process.env.HOME,
                }),
              )
              .pipe(Effect.orDie);
          }
        }),
      );
      const probe = yield* probeClaudeCapabilities(
        decodeClaudeSettings({ binaryPath: executable }),
        {
          PATH: process.env.PATH,
          HOME: home,
          USERPROFILE: home,
          CLAUDE_CONFIG_DIR: NodePath.join(home, ".claude"),
          CLAUDE_SECURESTORAGE_CONFIG_DIR: NodePath.join(home, "secure-storage"),
          XDG_CONFIG_HOME: NodePath.join(home, ".config"),
          TMPDIR: tmp,
          TMP: tmp,
          TEMP: tmp,
        },
        workspace,
      ).pipe(Effect.forkChild);
      if (!("constructionFailure" in testCase)) yield* Deferred.await(initStarted);
      if ("deadline" in testCase) {
        if (testCase.deadline === "usage") yield* Deferred.await(usageStarted);
        yield* TestClock.adjust(testCase.deadline === "init" ? "25 seconds" : "4 seconds");
      }
      let capabilities;
      if ("interrupt" in testCase) {
        if (testCase.interrupt === "usage") yield* Deferred.await(usageStarted);
        yield* Fiber.interrupt(probe);
        const exit = yield* Fiber.await(probe);
        assert.equal(Exit.isFailure(exit), true);
        if (Exit.isFailure(exit)) assert.equal(Cause.hasInterrupts(exit.cause), true);
      } else {
        capabilities = yield* Fiber.join(probe);
        if ("denied" in testCase) {
          assert.equal(capabilities, undefined);
        } else {
          assert.equal(capabilities?.email, "test@example.com");
          assert.equal(capabilities?.subscriptionType, "pro");
          assert.equal(capabilities?.tokenSource, "oauth");
          assert.deepEqual(capabilities?.slashCommands, []);
          assert.deepEqual(
            capabilities?.usage,
            testCase.mode === "success"
              ? { rate_limits_available: false, rate_limits: {} }
              : undefined,
          );
        }
      }
      if (!("constructionFailure" in testCase)) {
        assert.equal(closeCalled, true, "the probe must close its owned query");
        assert.equal(returnJoined, true, "the probe must await query.return()");
      }
      assert.equal(abortSignal?.aborted, true);
      assert.equal(
        exited,
        true,
        "the captured child must have exited before readiness or interruption completes",
      );
      assert.ok(child?.pid);
      assert.equal(requests.includes("user"), false, "no inference prompt may reach the peer");
    }).pipe(Effect.scoped),
  );

  it.effect("reports synchronous query construction failure as unavailable", () =>
    Effect.gen(function* () {
      const query = vi.spyOn(ClaudeSdk, "query").mockImplementation(() => {
        throw new Error("construction refused");
      });
      yield* Effect.addFinalizer(() => Effect.sync(() => query.mockRestore()));
      assert.equal(
        yield* probeClaudeCapabilities(decodeClaudeSettings({ binaryPath: "fixture-only" })),
        undefined,
      );
    }).pipe(Effect.scoped),
  );
});
