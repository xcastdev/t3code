// @effect-diagnostics nodeBuiltinImport:off
import * as NodeFSP from "node:fs/promises";
import { runtimeLoaderSource } from "../src/server/runtimeLoaderSource.ts";
import { runtimeLauncherSource } from "../src/server/runtimeLauncherSource.ts";

const files = [
  "bunfig.toml",
  "runtimeOptions.ts",
  "runtimeLoader.ts",
  "runtimeMain.ts",
  "runtimeLauncher.ts",
  "runtimePolicyHooks.ts",
  "policy.ts",
  "compatibility.ts",
  "recipe.ts",
  "controlChannel.ts",
];
const sources = Object.fromEntries(
  await Promise.all(
    files.map(async (name) => [
      name,
      await NodeFSP.readFile(new URL(`../src/server/${name}`, import.meta.url), "utf8"),
    ]),
  ),
);
sources["preload.ts"] = runtimeLoaderSource;
sources["launcher.ts"] = runtimeLauncherSource;
await NodeFSP.writeFile(
  new URL("../src/server/runtimeAssets.generated.ts", import.meta.url),
  `// Generated by scripts/generate-runtime-assets.ts.\nexport const runtimeAssetSources = ${JSON.stringify(sources, null, 2)} as const;\n`,
);
